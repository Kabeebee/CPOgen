"""Write a CPO2D .DAT input file (layout follows the CPO2D 3rd benchmark example).

Every line is ``values  comment``. Keyword tokens not visible in the benchmark
listing are collected in ``TOKENS`` so they can be adjusted in one place.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np

from .geometry import CpoGeometry

TOKENS = {
    "symmetry": "cylindrical symmetry",
    "electrode": "",        # prefix omitted: line reads "straight electrode ..."
    "no_more_electrodes": "",
}


def _f(x: float) -> str:
    return f"{x:.6g}"


def _lengths(points: np.ndarray) -> np.ndarray:
    return np.hypot(*np.diff(points, axis=0).T)


def format_dat(
    geo: CpoGeometry,
    title: str = "Tip-extractor model",
    segments: int = 400,
    charge_inaccuracy: float = 1e-4,
    print_level: str = "p",
) -> str:
    L: list[str] = []

    def add(v, c=""):
        L.append(f"{v}   {c}".strip())

    add(title, "-comments at end")
    add(TOKENS["symmetry"], "-cylindrical or planar symmetry?")
    add("tmp.dat", "name of hidden output file, for processed data")
    add("tmpa.dat", "name of main output file, for ray data")
    add(print_level, "n/p/m/a for nearlyzero/partial/most/all printing level")
    add("0", "voltage reflection symmetries in z=0 plane")
    add(len(geo.voltages_per_index), "number of different voltages")
    add(f"{_f(charge_inaccuracy)}   0", "allowed consistency error, allow outside z's")

    total_len = sum(_lengths(e.points).sum() for e in geo.electrodes)
    for e in geo.electrodes:
        seg_len = _lengths(e.points)
        # Subdivisions proportional to segment length, at least 1 each.
        subs = np.maximum(1, np.round(seg_len / total_len * segments)).astype(int)
        v = e.voltage_index
        for i, (p0, p1) in enumerate(zip(e.points[:-1], e.points[1:])):
            if i == 0:
                add(TOKENS["electrode"], f"straight electrode ({e.name})")
                add(f"{_f(p0[0])} {_f(p0[1])}", "r and z of first end")
            else:
                add("straight electrode")
                add("touching the previous electrode")
            add(f"{_f(p1[0])} {_f(p1[1])}", "r and z of second end")
            add(f"{v} {v}", "numbers of 2 applied voltages (can be same, for equipotential electrode)")
            add(f"{subs[i]} 1", "number of subdivisions, type of subdivision")
    add(TOKENS["no_more_electrodes"], "no more electrode information")
    add("0 1 0.5", "final number of segments, number of steps, weight")
    add(_f(charge_inaccuracy * 1e-3), "charge inacc, non-zero tot Q, improve matrix, space-chrg, import")
    add("constant applied voltages")
    for i in sorted(geo.voltages_per_index):
        add(_f(geo.voltages_per_index[i]), f"applied voltage {i} ({geo.electrodes[i - 1].name})")
    add("n", "no more magnetic fields from menu")
    add("n", "focal properties? (y/n)")
    add("n n n", "no more potentials and fields along a line")
    add("no ray information")
    L += [
        "",
        f"Generated by cpogen from an SEM tip profile. Lengths are in {geo.unit}; "
        "electrode 1 is the tip (apex at z=0), electrode 2 the extractor plate.",
    ]
    return "\n".join(L) + "\n"


def write_dat(path: str | Path, geo: CpoGeometry, **kw) -> None:
    Path(path).write_text(format_dat(geo, **kw), encoding="ascii", newline="\r\n")
